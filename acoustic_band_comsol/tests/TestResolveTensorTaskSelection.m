function testClampsRangeEnd(testCase)
cfg = struct( ...
    'tensor_dir', '', ...
    'tensor_files', {{ ...
        'case_01_tensor.mat', ...
        'case_02_tensor.mat', ...
        'case_03_tensor.mat'}}, ...
