function temp_dir = createTempTensorDir(testCase)
temp_dir = tempname;
mkdir(temp_dir);
testCase.addTeardown(@() rmdir(temp_dir, 's'));
end

function createTensorStub(folder, name)
fid = fopen(fullfile(folder, name), 'w');
fclose(fid);
end
